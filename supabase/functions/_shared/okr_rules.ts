// Каноничный набор правил аудита OKR (Doerr / OKR-PI).
// Используется И в draft-okr (самооценка score_hint), И в validate-okr (полный аудит) —
// чтобы оба модуля судили OKR по одной и той же шкале.

// ВАЖНО: идентификаторы правил ниже (OBJ-*, KR-*) — это ИМЕНА ПРАВИЛ АУДИТА,
// НЕ номера ключевых результатов пользователя. Когда ссылаешься на конкретный
// KR пользователя в hint/reasoning — указывай его по позиции ("второй KR",
// "KR №2"), а имя правила пиши как есть (KR-OUTCOME, KR-LEADING). Не смешивай:
// например, KR-OUTCOME — это правило о том, что KR описывают исходы, а не
// номер второго/третьего Key Result.
const BASE_RULES = `ВАЖНО: идентификаторы правил ниже (OBJ-*, KR-*) — это ИМЕНА ПРАВИЛ АУДИТА, а НЕ номера ключевых результатов пользователя. Когда ссылаешься на конкретный KR пользователя в hint/reasoning — указывай его по позиции ("второй KR", "KR №2"), а имя правила пиши как есть (KR-OUTCOME, KR-LEADING). Не смешивай: KR-OUTCOME — это правило о том, что KR описывают исходы, а не номер второго/третьего Key Result пользователя.

- OBJ-QUALITATIVE [important]  Objective качественный и вдохновляющий, не метрика.
- OBJ-AMBITIOUS [important]  Objective амбициозный, запоминающийся, по масштабу и смыслу соответствует выбранному горизонту (НЕ требует явного срока/даты/номера периода в тексте — горизонт уже зафиксирован отдельным полем "horizon").
- OBJ-NO-NUMBERS [critical]   В Objective НЕТ KPI, процентов и цифр.
- KR-MEASURABLE [critical]  Каждый KR измерим (число/метрика, не активность).
- KR-BASELINE-TARGET [critical]  У каждого KR явные baseline и target (FROM → TO). Это ОБЯЗАТЕЛЬНО распознавать и внутри обычного текста KR, не только в отдельных полях: формулировки вида «с X до Y», «X → Y», «вырастет/увеличится с X до Y», «с X% до Y%», «с 500 тысяч до 750 тысяч» — это ВАЛИДНЫЙ baseline→target в самом тексте, НЕ проваливай KR-BASELINE-TARGET из-за этого. Провал — только если в тексте KR и в полях baseline/target ДЕЙСТВИТЕЛЬНО нет ни одного числового ориентира ни для начала, ни для цели.
- KR-OUTCOME [critical]  KR описывают ИСХОДЫ, а не задачи. Запрещены корневые глаголы:
                  «провести», «поддержать», «запустить», «построить», «разработать», «внедрить»,
                  "conduct", "support", "build", "launch", "develop", "ship".
- KR-TIMEBOUND [important] KR ограничены по времени и имеют градиент прогресса (не бинарные).
- KR-LEADING [important] Хотя бы один KR — LEADING (опережающий) индикатор.
- KR-PERSPECTIVES [improve]  Набор KR сбалансирован по точкам зрения (AI-Native SAFe): КЛИЕНТ И БИЗНЕС (польза клиенту, который получает результат, и бизнесу, который от него зависит: опережающие сигналы реакции клиентов + запаздывающие показатели прибыли, удержания, влияния); ОСУЩЕСТВИМОСТЬ И РИСКИ (две функции: (а) осуществимость — «подтвердить/доказать, что это возможно», ранние доказательства жизнеспособности подхода; (б) защита критичного, «не сломать» — контр-метрика вида «удерживать X ниже/выше границы по мере того, как растёт основное». Оба типа — опережающие); ОБУЧЕНИЕ И РАЗВИТИЕ (чему организация научится: что показал прототип, что исключил эксперимент, что выявило тестирование на рынке — тоже опережающие). Это ПОДСКАЗКА для расширения мышления, НЕ требование: не все оси применимы к каждой цели. Провал только если ВСЕ KR относятся к одной оси И расширение набора очевидно уместно. В hint назови, какой оси не хватает, и приведи пример KR этой оси под данный Objective. Учитывай характер Objective: для НОВОГО/рискованного (запуск, эксперимент, новая технология/рынок, автоматизация ранее ручного) предлагай обе функции оси осуществимости (быстрая проверка «взлетит ли» + защита «не сломать критичное»), причём обе должны давать сигнал РАНО, в пределах одного под-периода горизонта; для оптимизации уже работающего — достаточно защитной метрики. НЕ требуй механически добавить KR ради заполнения всех трёх осей.`;

const SCORING_BLOCK = `SEVERITY:
- critical — без исправления OKR методологически некорректен.
- important — снижает качество, но OKR работоспособен.
- improve — точечное усиление формулировки.

SCORING (используй ЭТУ формулу для score_hint и для общего score):
weights: critical=3, important=2, improve=1.
score = round(100 * sum(weights of passed rules) / sum(weights of all rules)).
ЖЁСТКИЙ ПОТОЛОК: если провалено ≥1 правила с severity="critical" — score ≤ 60.`;

export const OKR_RULES_BLOCK = `OKR AUDIT RULES (canonical, single source of truth):

${BASE_RULES}

${SCORING_BLOCK}`;

// Дополнительный набор правил для квартального OKR (3 месяца).
// Применяется ПОВЕРХ базовых правил — KR-LEADING повышается до critical, добавляются Q-FOCUS/Q-THEME/Q-REACH.
export const OKR_RULES_BLOCK_QUARTER = `OKR AUDIT RULES — QUARTERLY OKR (3 months, canonical):

${BASE_RULES}

QUARTER-SPECIFIC OVERRIDES & ADDITIONS:
- KR-LEADING [critical, override]  Для квартала: хотя бы один KR ДОЛЖЕН быть LEADING. Без leading-индикатора квартальный OKR неуправляем — за 90 дней lag-метрика не успеет сдвинуться. Если ни одного leading KR нет, KR-LEADING → fail с severity=critical.
- Q-FOCUS [important]  Квартальный OKR: 1 Objective + 2..4 Key Results (3 — оптимум). Больше 4 — расфокусировка квартала, fail.
- Q-THEME [improve]  Objective связан с ОДНОЙ фокус-темой квартала, а не сборником разнородных инициатив. Если Objective склеивает 2+ независимые темы — fail.
- Q-REACH [important]  Дельта baseline→target должна быть достижима за 90 дней от текущей точки. Если target явно требует >1 квартала (например, годовая цель целиком перенесена в квартал) — fail с подсказкой «разбейте на кварталы».

${SCORING_BLOCK}`;

export function getRulesBlock(horizon?: string): string {
  return horizon === "quarter_3m" ? OKR_RULES_BLOCK_QUARTER : OKR_RULES_BLOCK;
}

// Горизонт-специфичные few-shot эталоны для KR-OUTCOME (outcome vs activity) и KR-LEADING
// (leading vs lagging). Симметричны по глубине для всех трёх горизонтов —
// отличаются ТОЛЬКО горизонтом замера и масштабом сдвига, чтобы строгость
// аудита не «плавала» между горизонтами.
//
// Осознанный размен: блок добавляет ~500-700 токенов к промпту validate-okr,
// но кратно повышает качество вердиктов (модель сравнивает формулировку с
// конкретным образцом, а не с абстрактным определением правила).
const FEWSHOT_STRATEGIC_3Y = `KR-OUTCOME (outcome vs activity) — горизонт 3 года:
- ПЛОХО: "Внедрить единый опросник по прозрачности процессов"
  → почему: действие/поставка, не результат. "Внедрили" ≠ "стало лучше".
- ОТЛИЧНО: "Доля сотрудников, отмечающих ясность процессов, выросла с 48% до 75% (замер раз в полугодие, трансформационный сдвиг за 3 года)"

KR-LEADING (leading vs lagging) — горизонт 3 года:
- ПЛОХО (lagging): "Retention rate вырос с 68% до 85%"
- ОТЛИЧНО (leading): "Доля клиентов, прошедших онбординг за <7 дней, выросла с 40% до 70% (опережающий сигнал retention, замер поквартально)"`;

const FEWSHOT_BLOCK_12M = `KR-OUTCOME (outcome vs activity) — годовой горизонт:
- ПЛОХО: "Запустить программу онбординга новых клиентов"
  → почему: факт запуска не гарантирует изменения.
- ОТЛИЧНО: "Доля новых клиентов, совершивших 5+ операций в первый месяц, выросла с 18% до 30% (замер поквартально, существенный сдвиг за год)"

KR-LEADING (leading vs lagging) — годовой горизонт:
- ПЛОХО (lagging): "eNPS вырос с 44% до 55%"
- ОТЛИЧНО (leading): "Частота использования ключевого сервиса выросла с 1.8 до 3.0 раза/мес на клиента (замер помесячно, драйвер eNPS)"`;

const FEWSHOT_QUARTER_3M = `KR-OUTCOME (outcome vs activity) — квартальный горизонт:
- ПЛОХО: "Провести 20 customer-интервью"
  → почему: счётчик активности, не изменение.
- ОТЛИЧНО: "Доля клиентов, называющих причиной ухода 'непонятные процессы', снизилась с 30% до 22% (замер помесячно, инкрементально за квартал)"

KR-LEADING (leading vs lagging) — квартальный горизонт:
- ПЛОХО (lagging): "Количество активных клиентов выросло с 1 до 1.2 млн"
- ОТЛИЧНО (leading): "% критичных межкомандных блокеров, решённых в SLA, вырос с 40% до 60% (замер по спринтам, опережает рост активности)"`;

const FEWSHOT_TESTS = `ТЕСТ ДЛЯ KR-OUTCOME: если KR выполнен на 100%, гарантирует ли это улучшение результата? Нет → это activity, провал KR-OUTCOME.
ТЕСТ ДЛЯ KR-LEADING: могу ли я повлиять на метрику за один под-период своего горизонта и увидеть сдвиг раньше финала? Да → leading.

Определение LEADING vs LAGGING: LAGGING — агрегат уже случившегося, виден пост-фактум (eNPS, retention, кол-во клиентов). LEADING — можно повлиять действием в пределах ОДНОГО под-периода и увидеть сдвиг раньше финального результата. Под-период зависит от горизонта: стратегия → квартал/полугодие; годовой OKR → квартал; квартальный OKR/solution → спринт/месяц.`;

export function getFewShotBlock(horizon?: string): string {
  const body = horizon === "quarter_3m"
    ? FEWSHOT_QUARTER_3M
    : horizon === "strategic_3y"
      ? FEWSHOT_STRATEGIC_3Y
      : FEWSHOT_BLOCK_12M;
  return `${body}\n\n${FEWSHOT_TESTS}`;
}


